"""Materialize GPU observations for a recorded ManiSkill state trajectory.

The M1-W formal data route must keep the action/state pairs from the existing
GPU-native source.  Re-executing those actions is not a valid way to produce
the training file: batched GPU physics can drift even when the initial state
and actions are identical.  This module therefore restores each recorded
``env_states`` frame on a CUDA ManiSkill environment and renders observations
without calling ``env.step``.

The resulting HDF5 file contains the source ``actions``, ``success`` and
``env_states`` byte-for-byte (apart from HDF5 container metadata), plus RGB and
proprioceptive observations generated by the same GPU backend.  Episode
identity is always checked with the frame-0 state fingerprint; seeds and HDF5
group order are not identity keys.
"""

from __future__ import annotations

import errno
import hashlib
import json
import math
import os
import shutil
import time
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import h5py
import numpy as np

from .state_identity import invert_unique_fingerprints, start_state_fingerprint


SCHEMA_VERSION = 1
CONTROL_MODE = "pd_ee_delta_pose"
BACKEND = "physx_cuda"
CAMERAS = ("base_camera", "hand_camera")


def _jsonable(value: Any) -> Any:
    if hasattr(value, "detach") and hasattr(value, "cpu") and hasattr(value, "numpy"):
        return _jsonable(value.detach().cpu().numpy())
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Path):
        return value.as_posix()
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError("JSON payload contains NaN or Infinity")
    return value


def _read_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise TypeError(f"Expected a JSON object at {path}")
    return payload


def _write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        temporary.write_text(
            json.dumps(_jsonable(payload), ensure_ascii=False, indent=2, allow_nan=False) + "\n",
            encoding="utf-8",
        )
        try:
            temporary.replace(path)
        except OSError as exc:
            if exc.errno != errno.EXDEV:
                raise
            shutil.copy2(temporary, path)
            temporary.unlink(missing_ok=True)
    finally:
        temporary.unlink(missing_ok=True)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _relative(path: Path) -> str:
    try:
        from robot_practice.evaluation.common import practice_root

        return path.resolve().relative_to(practice_root()).as_posix()
    except ValueError:
        return path.as_posix()


def _state_list(group: h5py.Group) -> list[dict[str, Any]]:
    from mani_skill.trajectory import utils as trajectory_utils

    if "env_states" not in group:
        raise RuntimeError(f"{group.name} has no env_states")
    return trajectory_utils.dict_to_list_of_dicts(group["env_states"])


def _batch_states(states: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    from mani_skill.trajectory import utils as trajectory_utils

    return trajectory_utils.list_of_dicts_to_dict(list(states))


def _records(metadata: Mapping[str, Any]) -> dict[int, dict[str, Any]]:
    values = metadata.get("episodes")
    if not isinstance(values, list):
        raise TypeError("Source metadata must contain an episodes list")
    result: dict[int, dict[str, Any]] = {}
    for value in values:
        if not isinstance(value, Mapping):
            raise TypeError("Each episode metadata record must be an object")
        episode_id = int(value["episode_id"])
        if episode_id in result:
            raise ValueError(f"Duplicate source episode id: {episode_id}")
        result[episode_id] = dict(value)
    return result


def _create_observation_datasets(group: h5py.Group, length: int) -> dict[str, h5py.Dataset]:
    """Create the non-privileged observation projection used by M1-W."""

    obs = group.create_group("obs")
    agent = obs.create_group("agent")
    sensor_data = obs.create_group("sensor_data")
    qpos = agent.create_dataset("qpos", shape=(length + 1, 9), dtype="f4")
    qvel = agent.create_dataset("qvel", shape=(length + 1, 9), dtype="f4")
    datasets: dict[str, h5py.Dataset] = {"qpos": qpos, "qvel": qvel}
    for camera in CAMERAS:
        camera_group = sensor_data.create_group(camera)
        datasets[camera] = camera_group.create_dataset(
            "rgb",
            shape=(length + 1, 128, 128, 3),
            dtype="u1",
            chunks=(1, 128, 128, 3),
            compression="gzip",
            compression_opts=1,
            shuffle=True,
        )
    return datasets


def _publish_directory(temporary: Path, destination: Path) -> None:
    if destination.exists():
        raise FileExistsError(f"Refusing to overwrite existing output: {destination}")
    try:
        temporary.replace(destination)
    except OSError as exc:
        if exc.errno != errno.EXDEV:
            raise
        shutil.copytree(temporary, destination, symlinks=False)
        shutil.rmtree(temporary)


def _copy_source_payload(source: h5py.Group, target: h5py.Group) -> None:
    for key in source.keys():
        if key != "obs":
            source.copy(key, target, name=key)


def _tensor_numpy(value: Any, *, dtype: np.dtype[Any] | None = None) -> np.ndarray:
    if hasattr(value, "detach") and hasattr(value, "cpu") and hasattr(value, "numpy"):
        value = value.detach().cpu().numpy()
    result = np.asarray(value)
    if dtype is not None:
        result = result.astype(dtype, copy=False)
    return result


def _materialize_batch(
    *,
    env: Any,
    source_file: h5py.File,
    output_file: h5py.File,
    episode_ids: Sequence[int],
    device: Any,
) -> tuple[int, int]:
    import torch

    ids = [int(value) for value in episode_ids]
    states_by_id: dict[int, list[dict[str, Any]]] = {}
    actions_by_id: dict[int, np.ndarray] = {}
    for episode_id in ids:
        source = source_file[f"traj_{episode_id}"]
        actions = np.asarray(source["actions"], dtype=np.float32)
        states = _state_list(source)
        if actions.ndim != 2 or actions.shape[1] != 7:
            raise ValueError(f"traj_{episode_id} actions must have shape [T,7], got {actions.shape}")
        if len(states) != actions.shape[0] + 1:
            raise ValueError(
                f"traj_{episode_id} has {len(states)} env states for {actions.shape[0]} actions"
            )
        if not np.isfinite(actions).all():
            raise ValueError(f"traj_{episode_id} contains non-finite actions")
        states_by_id[episode_id] = states
        actions_by_id[episode_id] = actions
        target = output_file.create_group(f"traj_{episode_id}")
        _copy_source_payload(source, target)
        _create_observation_datasets(target, int(actions.shape[0]))

    lengths = {episode_id: int(actions_by_id[episode_id].shape[0]) for episode_id in ids}
    max_length = max(lengths.values())
    seed = torch.arange(len(ids), dtype=torch.int64, device=device)
    env.reset(seed=seed)

    # There is deliberately no env.step here.  Each rendered frame is obtained
    # from the exact source state at that frame.
    for frame_index in range(max_length + 1):
        state_batch = [
            states_by_id[episode_id][min(frame_index, lengths[episode_id])]
            for episode_id in ids
        ]
        env.unwrapped.set_state_dict(_batch_states(state_batch))
        env.unwrapped.scene._gpu_fetch_all()
        observation = env.unwrapped.get_obs()
        qpos = _tensor_numpy(observation["agent"]["qpos"], dtype=np.float32)
        qvel = _tensor_numpy(observation["agent"]["qvel"], dtype=np.float32)
        images = {
            camera: _tensor_numpy(
                observation["sensor_data"][camera]["rgb"], dtype=np.uint8
            )
            for camera in CAMERAS
        }
        if qpos.shape != (len(ids), 9) or qvel.shape != (len(ids), 9):
            raise RuntimeError(f"Unexpected proprioception shape: qpos={qpos.shape}, qvel={qvel.shape}")
        if any(image.shape != (len(ids), 128, 128, 3) for image in images.values()):
            raise RuntimeError(f"Unexpected RGB shape: {[(key, value.shape) for key, value in images.items()]}")
        for index, episode_id in enumerate(ids):
            if frame_index > lengths[episode_id]:
                continue
            datasets = output_file[f"traj_{episode_id}"]["obs"]
            datasets["agent"]["qpos"][frame_index] = qpos[index]
            datasets["agent"]["qvel"][frame_index] = qvel[index]
            for camera in CAMERAS:
                datasets["sensor_data"][camera]["rgb"][frame_index] = images[camera][index]

    return sum(lengths.values()), sum(length + 1 for length in lengths.values())


def materialize(
    *,
    source_h5: str | Path,
    output_dir: str | Path,
    task_id: str = "StackCube-v1",
    num_envs: int = 100,
    expected_episodes: int | None = None,
) -> dict[str, Any]:
    """Render a complete GPU-native source into an RGB/state trajectory file."""

    source_h5 = Path(source_h5).expanduser().resolve()
    output_dir = Path(output_dir).expanduser().resolve()
    source_json = source_h5.with_suffix(".json")
    if not source_h5.is_file() or not source_json.is_file():
        raise FileNotFoundError(f"GPU-native source H5/JSON pair is missing: {source_h5}")
    if num_envs <= 0:
        raise ValueError("num_envs must be positive")

    metadata = _read_json(source_json)
    records = _records(metadata)
    source_episode_by_target = {
        int(episode_id): int(record.get("source_episode_id", episode_id))
        for episode_id, record in records.items()
    }
    env_info = metadata.get("env_info")
    if not isinstance(env_info, Mapping):
        raise TypeError("Source metadata has no env_info")
    source_kwargs = env_info.get("env_kwargs")
    if not isinstance(source_kwargs, Mapping):
        raise TypeError("Source metadata has no env_info.env_kwargs")
    if source_kwargs.get("control_mode") != CONTROL_MODE:
        raise ValueError(f"GPU-native source control mode is not {CONTROL_MODE}")
    if source_kwargs.get("sim_backend") != BACKEND:
        raise ValueError(f"GPU-native source backend is not {BACKEND}")
    ids = sorted(records)
    if expected_episodes is not None:
        ids = ids[: int(expected_episodes)]
    if not ids:
        raise ValueError("GPU-native source contains no episodes")
    if len(ids) > len(records):
        raise ValueError("expected_episodes exceeds source episode count")

    output_dir.parent.mkdir(parents=True, exist_ok=True)
    manifest_path = output_dir / "materialization_manifest.json"
    final_h5 = output_dir / "replay.h5"
    final_json = output_dir / "replay.json"
    if manifest_path.is_file() and final_h5.is_file() and final_json.is_file():
        return _read_json(manifest_path)
    if output_dir.exists():
        raise FileExistsError(f"Incomplete GPU state materialization exists: {output_dir}")

    import gymnasium as gym
    import mani_skill.envs  # noqa: F401

    source_fingerprints: dict[int, str] = {}
    episode_lengths: dict[int, int] = {}
    source_once = 0
    source_end = 0
    with h5py.File(source_h5, "r") as source_file:
        for episode_id in ids:
            source = source_file[f"traj_{episode_id}"]
            source_fingerprints[episode_id] = start_state_fingerprint(source, tolerance=1e-4)
            episode_lengths[episode_id] = int(source["actions"].shape[0])
            success = np.asarray(source["success"], dtype=bool).reshape(-1)
            if success.size != episode_lengths[episode_id]:
                raise ValueError(f"traj_{episode_id} success/action length mismatch")
            source_once += int(bool(success.any()))
            source_end += int(bool(success[-1]))
    invert_unique_fingerprints(source_fingerprints, label="GPU-native source")

    # Grouping similarly long episodes avoids padding a very long trajectory
    # into every shorter CUDA environment in the same batch.
    execution_ids = sorted(ids, key=lambda value: (episode_lengths[value], value))
    protocol_kwargs = dict(source_kwargs)
    protocol_kwargs.update(
        {
            "obs_mode": "rgb",
            "control_mode": CONTROL_MODE,
            "sim_backend": BACKEND,
            "render_mode": "rgb_array",
            "reward_mode": "sparse",
            "reconfiguration_freq": 1,
        }
    )
    temporary = output_dir.parent / f".{output_dir.name}.incomplete-{os.getpid()}"
    if temporary.exists():
        raise FileExistsError(f"Incomplete materialization directory exists: {temporary}")
    temporary.mkdir(parents=True)
    started = time.monotonic()
    total_actions = 0
    total_observation_frames = 0
    batch_stats: list[dict[str, Any]] = []
    try:
        import torch

        with h5py.File(source_h5, "r") as source_file, h5py.File(
            temporary / "replay.h5", "w"
        ) as output_file:
            for start in range(0, len(execution_ids), int(num_envs)):
                batch_ids = execution_ids[start : start + int(num_envs)]
                batch_kwargs = dict(protocol_kwargs)
                batch_kwargs["num_envs"] = len(batch_ids)
                env = gym.make(task_id, **batch_kwargs)
                try:
                    actions, observations = _materialize_batch(
                        env=env,
                        source_file=source_file,
                        output_file=output_file,
                        episode_ids=batch_ids,
                        device=env.unwrapped.device,
                    )
                finally:
                    env.close()
                total_actions += actions
                total_observation_frames += observations
                batch_stat = {
                    "start_index": int(start),
                    "episode_count": len(batch_ids),
                    "total_action_steps": int(actions),
                    "max_action_steps": max(episode_lengths[value] for value in batch_ids),
                }
                batch_stats.append(batch_stat)
                elapsed = time.monotonic() - started
                print(
                    f"[gpu-state-materialization] {min(start + len(batch_ids), len(ids))}/{len(ids)} "
                    f"episodes, {total_observation_frames} observation frames, {elapsed:.1f}s",
                    flush=True,
                )
            output_file.flush()

        output_metadata = json.loads(json.dumps(_jsonable(metadata)))
        output_env_info = output_metadata["env_info"]
        output_env_info["env_kwargs"] = dict(output_env_info["env_kwargs"])
        output_env_info["env_kwargs"].update(protocol_kwargs)
        output_env_info["env_kwargs"]["num_envs"] = int(num_envs)
        output_metadata["source_type"] = "gpu_state_materialization"
        output_metadata["source_desc"] = (
            "GPU-rendered observations materialized from exact GPU-native env_states; "
            "source actions are not re-executed"
        )
        output_metadata["episodes"] = []
        for episode_id in ids:
            record = dict(records[episode_id])
            source_episode_id = source_episode_by_target[episode_id]
            record["episode_id"] = int(episode_id)
            # Preserve provenance when materializing a derived direct-RGB
            # capture.  For the formal source this is the same ID, but for a
            # merged replay the destination traj_N is not the source ID.
            record["source_episode_id"] = source_episode_id
            record["materialized_episode_id"] = int(episode_id)
            record["source_start_state_fingerprint"] = source_fingerprints[episode_id]
            record["target_start_state_fingerprint"] = source_fingerprints[episode_id]
            record.pop("episode_seed", None)
            reset_kwargs = record.get("reset_kwargs")
            if isinstance(reset_kwargs, dict):
                reset_kwargs.pop("seed", None)
            output_metadata["episodes"].append(record)
        output_metadata["m1_wam_data_route"] = {
            "route": "gpu_native_state_materialization_7d",
            "source_h5": _relative(source_h5),
            "backend": BACKEND,
            "control_mode": CONTROL_MODE,
            "action_dim": 7,
            "state_projection": ["agent.qpos", "agent.qvel"],
            "cameras": [f"sensor_data.{camera}.rgb" for camera in CAMERAS],
            "env_step_called": False,
            "action_replay_used": False,
            "identity": "env_states frame 0 fingerprint",
            "seed_is_not_identity": True,
        }
        _write_json(temporary / "replay.json", output_metadata)

        target_fingerprints: dict[int, str] = {}
        with h5py.File(temporary / "replay.h5", "r") as output_file:
            for episode_id in ids:
                group = output_file[f"traj_{episode_id}"]
                target_fingerprints[episode_id] = start_state_fingerprint(group, tolerance=1e-4)
                if group["obs"]["agent"]["qpos"].shape != (episode_lengths[episode_id] + 1, 9):
                    raise RuntimeError(f"Invalid qpos timeline for traj_{episode_id}")
        identity_gate = target_fingerprints == source_fingerprints
        if not identity_gate:
            raise RuntimeError("GPU state materialization changed the source fingerprint set")

        destination_manifest = {
            "schema_version": SCHEMA_VERSION,
            "task": str(env_info.get("env_id", task_id)),
            "route": "gpu_native_state_materialization_7d",
            "source_h5": _relative(source_h5),
            "source_sha256": _sha256(source_h5),
            "replay_h5": _relative(output_dir / "replay.h5"),
            "replay_json": _relative(output_dir / "replay.json"),
            "backend": BACKEND,
            "control_mode": CONTROL_MODE,
            "action_dim": 7,
            "num_envs": int(num_envs),
            "episode_count": len(ids),
            "expected_episodes": expected_episodes,
            "total_action_steps": int(total_actions),
            "total_observation_frames": int(total_observation_frames),
            "source_success_once": int(source_once),
            "source_success_at_end": int(source_end),
            "action_replay_used": False,
            "env_step_called": False,
            "execution_order": "ascending_episode_length_then_episode_id",
            "batch_stats": batch_stats,
            "identity": {
                "key": "start_state_fingerprint from env_states frame 0",
                "tolerance": 1e-4,
                "source_unique_count": len(source_fingerprints),
                "target_unique_count": len(target_fingerprints),
                "exact_source_coverage": identity_gate,
                "seed_is_not_identity": True,
            },
            "observation_schema": {
                "state": {"agent.qpos": [9], "agent.qvel": [9]},
                "rgb": {camera: [128, 128, 3] for camera in CAMERAS},
            },
            "gate_pass": len(ids) == (expected_episodes or len(ids)) and identity_gate,
        }
        _write_json(temporary / "materialization_manifest.json", destination_manifest)
        _publish_directory(temporary, output_dir)
    except BaseException:
        if temporary.exists():
            shutil.rmtree(temporary)
        raise
    return destination_manifest


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-h5", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--task", default="StackCube-v1")
    parser.add_argument("--num-envs", type=int, default=100)
    parser.add_argument("--expected-episodes", type=int, default=None)
    args = parser.parse_args(argv)
    result = materialize(
        source_h5=args.source_h5,
        output_dir=args.output_dir,
        task_id=args.task,
        num_envs=args.num_envs,
        expected_episodes=args.expected_episodes,
    )
    print(json.dumps(_jsonable(result), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
